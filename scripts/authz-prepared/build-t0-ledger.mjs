// Byte-safe extractor for the canonical-operation ledger + flag storage-hardening
// slices out of the BLOCKED IE-writer artifact 20260716180000. The payment/credit
// cutover (runbook domain #1) needs the ledger WITHOUT pulling the income-expense
// writer along; the flag hardening is domain-agnostic defense-in-depth for every
// CANARY row. Do not hand-edit the outputs; edit the artifact and regenerate.
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync(
  'supabase/migrations/20260716180000_t5_income_expense_create_draft_writer.sql', 'utf8');

function cut(startAnchor, endAnchor, label) {
  const s = src.indexOf(startAnchor);
  if (s < 0) throw new Error(`${label}: start anchor not found`);
  const e = src.indexOf(endAnchor, s);
  if (e < 0) throw new Error(`${label}: end anchor not found`);
  return src.slice(s, e + endAnchor.length);
}

// Ledger part A: table + retrofit checks + index + completion check + table REVOKE.
const ledgerTable = cut(
  'CREATE TABLE IF NOT EXISTS app_private.canonical_write_operations (',
  `REVOKE ALL ON app_private.canonical_write_operations
  FROM PUBLIC, anon, authenticated, service_role;`,
  'ledger table');

// Ledger part B: append-only/immutability guard + its REVOKE + both triggers.
const ledgerGuard = cut(
  'CREATE OR REPLACE FUNCTION app_private.guard_canonical_write_operation()',
  `CREATE TRIGGER canonical_write_operations_no_truncate
BEFORE TRUNCATE ON app_private.canonical_write_operations
FOR EACH STATEMENT EXECUTE FUNCTION app_private.guard_canonical_write_operation();`,
  'ledger guard');

// Flag storage hardening: finite values + CANARY completeness checks.
const flagHardening = cut(
  '-- Close malformed rollout configurations at storage level as well as in the',
  `  ALTER TABLE app_private.server_feature_flags
    VALIDATE CONSTRAINT server_feature_flags_canary_limits_check;
END;
$function$;`,
  'flag hardening');

const stamp = (title, body) => `-- ============================================================================
-- ${title}
-- STATUS: PREPARED. NOT a migration; production apply gated by owner (runbook
-- RUNBOOK-CUTOVER-PAYMENT.md). GENERATED by build-t0-ledger.mjs from the BLOCKED
-- artifact 20260716180000 — do not hand-edit; edit the artifact and regenerate.
-- Prerequisites: app_private schema + server_feature_flags (T5-infra
-- 20260716120200, APPLIED on production 2026-07-16). Idempotent by construction
-- (IF NOT EXISTS / OR REPLACE / DROP TRIGGER IF EXISTS) — safe on targets where
-- the objects already exist (e.g. staging installed via the full artifact).
-- ============================================================================

begin;

${body}

commit;
`;

writeFileSync('scripts/authz-prepared/t0_ledger_only.sql', stamp(
  'T0 PREPARED SQL — canonical_write_operations ledger ONLY (+ append-only guard)',
  ledgerTable + '\n\n' + ledgerGuard));
writeFileSync('scripts/authz-prepared/t0_flag_hardening.sql', stamp(
  'T0 PREPARED SQL — server_feature_flags storage-level hardening ONLY',
  flagHardening));
console.log('written t0_ledger_only.sql', (ledgerTable + ledgerGuard).length,
  'bytes body; t0_flag_hardening.sql', flagHardening.length, 'bytes body');
