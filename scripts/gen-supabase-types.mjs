import { spawn } from 'node:child_process';
import { open, readFile, rename, rm } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import { basename, dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const GENERATED_TYPES_HEADER = '// This file is automatically generated. Do not edit it directly.';
export const SUPABASE_CLI_VERSION = '2.109.1';
export const POSTGRES_META_VERSION = '0.96.6';
export const PGLITE_SOCKET_VERSION = '0.2.7';

const DEFAULT_REPO_ROOT = fileURLToPath(new URL('..', import.meta.url));
const PROJECT_REF_PATTERN = /^[a-z0-9]{20}$/;
const ACCESS_TOKEN_PATTERN = /\bsbp_[A-Za-z0-9_-]+\b/;
const SAFE_CHILD_ENV_KEYS = Object.freeze([
  'PATH', 'Path', 'PATHEXT', 'SystemRoot', 'SYSTEMROOT', 'WINDIR',
  'ComSpec', 'COMSPEC', 'TEMP', 'TMP', 'TMPDIR', 'HOME', 'USERPROFILE',
  'APPDATA', 'LOCALAPPDATA', 'LANG', 'LC_ALL', 'TZ', 'PGTZ', 'CI',
  'NO_COLOR', 'FORCE_COLOR', 'NODE_EXTRA_CA_CERTS', 'SSL_CERT_FILE',
  'SSL_CERT_DIR', 'npm_config_cache', 'NPM_CONFIG_CACHE',
  'npm_config_prefix', 'NPM_CONFIG_PREFIX', 'npm_execpath',
  'npm_node_execpath', 'npm_config_user_agent', 'SUPABASE_TYPES_SOURCE',
  'SUPABASE_TYPES_LOCAL_ENGINE', 'OPENCLAW_POSTGRES_BIN',
]);

export function buildMinimalChildEnvironment(environment = process.env, overrides = {}) {
  const childEnvironment = {};
  for (const key of SAFE_CHILD_ENV_KEYS) {
    if (environment[key] !== undefined) childEnvironment[key] = environment[key];
  }
  for (const [key, value] of Object.entries(overrides)) {
    if (value !== undefined) childEnvironment[key] = String(value);
  }
  return childEnvironment;
}

function parsePackageJson(packageJson) {
  try {
    return JSON.parse(packageJson);
  } catch {
    return {};
  }
}

export function resolveProjectRef({ configToml = '', linkedProjectRef = '', packageJson = '' }) {
  const packageData = parsePackageJson(packageJson);
  const legacyScript = packageData.scripts?.['gen:types'] ?? '';
  const candidates = [
    configToml.match(/^\s*project_id\s*=\s*["']([^"']+)["']/m)?.[1],
    linkedProjectRef.trim(),
    packageData.config?.supabaseProjectRef,
    legacyScript.match(/--project-id(?:=|\s+)([a-z0-9]+)/)?.[1],
  ];
  const projectRef = candidates.find((candidate) => PROJECT_REF_PATTERN.test(candidate ?? ''));

  if (!projectRef) {
    throw new Error(
      'Could not resolve a valid Supabase project ref from supabase/config.toml, linked config, or package.json.',
    );
  }

  return projectRef;
}

export function extractSupabaseAccessToken({ environment = process.env, localConfig = '' }) {
  const token =
    environment.SUPABASE_ACCESS_TOKEN?.trim() ||
    environment.SUPABASE_PAT?.trim() ||
    localConfig.match(ACCESS_TOKEN_PATTERN)?.[0] ||
    '';

  if (!ACCESS_TOKEN_PATTERN.test(token)) {
    throw new Error(
      'Could not find a Supabase access token in SUPABASE_ACCESS_TOKEN, SUPABASE_PAT, or CLAUDE.local.md.',
    );
  }

  return token;
}

export function redactSecrets(value, knownSecrets = []) {
  let redacted = String(value ?? '');
  for (const secret of knownSecrets) {
    if (secret) redacted = redacted.replaceAll(secret, '[REDACTED]');
  }
  return redacted.replace(/\bsbp_[A-Za-z0-9_-]+\b/g, '[REDACTED]');
}

export function buildGeneratedTypesFile(generatedOutput) {
  let normalized = String(generatedOutput).replace(/^\uFEFF/, '').replace(/\r\n?/g, '\n');
  if (normalized.startsWith(`${GENERATED_TYPES_HEADER}\n`)) {
    normalized = normalized.slice(GENERATED_TYPES_HEADER.length + 1);
  }
  normalized = normalized.replace(/^\n+/, '').replace(/\s*$/, '\n');

  if (!normalized.startsWith('export type Json =') || !/^export type Database\s*=/m.test(normalized)) {
    throw new Error('Supabase CLI did not return valid TypeScript database types.');
  }

  return `${GENERATED_TYPES_HEADER}\n${normalized}`;
}

function findObjectSection(lines, sectionName) {
  const start = lines.findIndex((line) => line === `    ${sectionName}: {`);
  if (start < 0) {
    throw new Error(`Generated types are missing public.${sectionName}.`);
  }
  const end = lines.findIndex(
    (line, index) => index > start && line === '    }',
  );
  if (end < 0) {
    throw new Error(`Generated types have an unterminated public.${sectionName}.`);
  }
  return { start, end };
}

function parseSectionEntries(lines, sectionName) {
  const { start, end } = findObjectSection(lines, sectionName);
  const starts = [];
  for (let index = start + 1; index < end; index += 1) {
    const match = /^      ([A-Za-z_][A-Za-z0-9_]*):(?: |{)/.exec(lines[index]);
    if (match) starts.push({ index, name: match[1] });
  }
  const entries = new Map();
  for (let index = 0; index < starts.length; index += 1) {
    const current = starts[index];
    const next = starts[index + 1]?.index ?? end;
    entries.set(current.name, lines.slice(current.index, next));
  }
  return { start, end, entries };
}

function mergeTableObjectFields(baselineBlock, generatedBlock) {
  let merged = [...baselineBlock];
  for (const objectName of ['Row', 'Insert', 'Update']) {
    const mergeObject = (block, sourceBlock) => {
      const start = block.findIndex((line) => line === `        ${objectName}: {`);
      const sourceStart = sourceBlock.findIndex(
        (line) => line === `        ${objectName}: {`,
      );
      if (start < 0 || sourceStart < 0) {
        throw new Error(`Table type is missing ${objectName}.`);
      }
      const end = block.findIndex(
        (line, index) => index > start && line === '        }',
      );
      const sourceEnd = sourceBlock.findIndex(
        (line, index) => index > sourceStart && line === '        }',
      );
      if (end < 0 || sourceEnd < 0) {
        throw new Error(`Table type has an unterminated ${objectName}.`);
      }
      const fields = new Map();
      for (const line of block.slice(start + 1, end)) {
        const match = /^          ([A-Za-z_][A-Za-z0-9_]*)(?:\?)?:/.exec(line);
        if (match) fields.set(match[1], line);
      }
      for (const line of sourceBlock.slice(sourceStart + 1, sourceEnd)) {
        const match = /^          (openclaw_[A-Za-z0-9_]*)(?:\?)?:/.exec(line);
        if (match) fields.set(match[1], line);
      }
      const sorted = [...fields.entries()]
        .sort(([left], [right]) => left.localeCompare(right))
        .map(([, line]) => line);
      return [...block.slice(0, start + 1), ...sorted, ...block.slice(end)];
    };
    merged = mergeObject(merged, generatedBlock);
  }
  return merged;
}

function replaceSectionEntries(lines, sectionName, generatedLines) {
  const baselineSection = parseSectionEntries(lines, sectionName);
  const generatedSection = parseSectionEntries(generatedLines, sectionName);
  const entries = new Map(baselineSection.entries);
  for (const [name, block] of generatedSection.entries) {
    if (name.startsWith('openclaw_')) entries.set(name, block);
  }
  if (sectionName === 'Tables') {
    for (const tableName of ['lead_activities', 'leads', 'rooms']) {
      const baselineBlock = entries.get(tableName);
      const generatedBlock = generatedSection.entries.get(tableName);
      if (!baselineBlock && !generatedBlock) continue;
      if (!baselineBlock || !generatedBlock) {
        throw new Error(`Cannot merge OpenClaw columns into public.${tableName}.`);
      }
      entries.set(
        tableName,
        mergeTableObjectFields(baselineBlock, generatedBlock),
      );
    }
  }
  const mergedEntries = [...entries.entries()]
    .sort(([left], [right]) => left.localeCompare(right))
    .flatMap(([, block]) => block);
  return [
    ...lines.slice(0, baselineSection.start + 1),
    ...mergedEntries,
    ...lines.slice(baselineSection.end),
  ];
}

export function mergeOpenClawGeneratedTypes(baselineOutput, generatedOutput) {
  const baseline = String(baselineOutput)
    .replace(/^\uFEFF/, '')
    .replace(/\r\n?/g, '\n')
    .replace(`${GENERATED_TYPES_HEADER}\n`, '');
  const generated = String(generatedOutput)
    .replace(/^\uFEFF/, '')
    .replace(/\r\n?/g, '\n')
    .replace(`${GENERATED_TYPES_HEADER}\n`, '');
  if (
    !baseline.startsWith('export type Json =') ||
    !generated.startsWith('export type Json =')
  ) {
    throw new Error('OpenClaw type merge requires two valid generated type files.');
  }
  let lines = baseline.replace(/\s*$/, '\n').split('\n');
  const generatedLines = generated.replace(/\s*$/, '\n').split('\n');
  for (const sectionName of [
    'Tables',
    'Views',
    'Functions',
    'Enums',
    'CompositeTypes',
  ]) {
    lines = replaceSectionEntries(lines, sectionName, generatedLines);
  }
  const merged = lines.join('\n').replace(/\s*$/, '\n');
  if (
    !merged.includes('      openclaw_accounts: {') ||
    !merged.includes('openclaw_schedule_revision')
  ) {
    throw new Error('OpenClaw generated types are incomplete after merge.');
  }
  return merged;
}

export function buildSupabaseCliInvocation(
  projectRef,
  platform = process.platform,
  {
    execPath = process.execPath,
    npmExecPath = process.env.npm_execpath,
    source = 'project',
  } = {},
) {
  const generatorArgs = [
    'gen',
    'types',
    'typescript',
    ...(source === 'local' ? ['--local'] : ['--project-id', projectRef]),
    '--schema',
    'public',
  ];

  if (platform === 'win32') {
    const npmCliPath =
      npmExecPath || join(dirname(execPath), 'node_modules', 'npm', 'bin', 'npm-cli.js');
    return {
      command: execPath,
      args: [
        npmCliPath,
        'exec',
        '--yes',
        '--package',
        `supabase@${SUPABASE_CLI_VERSION}`,
        '--',
        'supabase',
        ...generatorArgs,
      ],
      shell: false,
    };
  }

  return {
    command: 'npx',
    args: ['--yes', `supabase@${SUPABASE_CLI_VERSION}`, ...generatorArgs],
    shell: false,
  };
}

export function captureCliOutput({ command, args, cwd, env, shell = false }) {
  return new Promise((resolvePromise, rejectPromise) => {
    const child = spawn(command, args, {
      cwd,
      env,
      shell,
      stdio: ['ignore', 'pipe', 'pipe'],
      windowsHide: true,
    });
    const stdoutChunks = [];
    const stderrChunks = [];

    child.stdout.on('data', (chunk) => stdoutChunks.push(chunk));
    child.stderr.on('data', (chunk) => stderrChunks.push(chunk));
    child.once('error', rejectPromise);
    child.once('close', (exitCode) => {
      try {
        const decoder = new TextDecoder('utf-8', { fatal: true });
        resolvePromise({
          exitCode: exitCode ?? 1,
          stdout: decoder.decode(Buffer.concat(stdoutChunks)),
          stderr: decoder.decode(Buffer.concat(stderrChunks)),
        });
      } catch {
        rejectPromise(new Error('Supabase CLI returned output that is not valid UTF-8.'));
      }
    });
  });
}

export function buildOpenClawPgliteTypegenInvocation(
  repoRoot,
  platform = process.platform,
  {
    execPath = process.execPath,
    npmExecPath = process.env.npm_execpath,
  } = {},
) {
  const packages = [
    `@supabase/postgres-meta@${POSTGRES_META_VERSION}`,
    `@electric-sql/pglite-socket@${PGLITE_SOCKET_VERSION}`,
    '@electric-sql/pglite@0.5.4',
  ];
  const scriptPath = join(repoRoot, 'scripts', 'generate-openclaw-pglite-types.mjs');
  if (platform === 'win32') {
    const npmCliPath =
      npmExecPath || join(dirname(execPath), 'node_modules', 'npm', 'bin', 'npm-cli.js');
    return {
      command: execPath,
      args: [
        npmCliPath,
        'exec',
        '--yes',
        ...packages.flatMap((packageName) => ['--package', packageName]),
        '--',
        'node',
        scriptPath,
      ],
      shell: false,
    };
  }
  return {
    command: 'npx',
    args: [
      '--yes',
      ...packages.flatMap((packageName) => ['--package', packageName]),
      '--',
      'node',
      scriptPath,
    ],
    shell: false,
  };
}

export async function generateOpenClawPgliteTypeOutput({
  repoRoot = DEFAULT_REPO_ROOT,
  environment = process.env,
  platform = process.platform,
  runProcess = captureCliOutput,
} = {}) {
  const invocation = buildOpenClawPgliteTypegenInvocation(repoRoot, platform, {
    npmExecPath: environment.npm_execpath,
  });
  const childEnvironment = buildMinimalChildEnvironment(environment);
  const result = await runProcess({
    ...invocation,
    cwd: repoRoot,
    env: childEnvironment,
  });
  delete childEnvironment.SUPABASE_PAT;
  delete childEnvironment.SUPABASE_ACCESS_TOKEN;
  if (result.exitCode !== 0) {
    const details = redactSecrets(result.stderr.trim()).slice(0, 2_000);
    throw new Error(
      `Pinned postgres-meta PGlite generator exited with code ${result.exitCode}.${details ? ` ${details}` : ''}`,
    );
  }
  return result.stdout;
}

export async function atomicWriteUtf8(targetPath, contents) {
  const tempPath = join(
    dirname(targetPath),
    `.${basename(targetPath)}.${process.pid}.${randomUUID()}.tmp`,
  );
  let fileHandle;

  try {
    fileHandle = await open(tempPath, 'wx', 0o600);
    await fileHandle.writeFile(contents, { encoding: 'utf8' });
    await fileHandle.sync();
    await fileHandle.close();
    fileHandle = undefined;
    await rename(tempPath, targetPath);
  } finally {
    if (fileHandle) await fileHandle.close().catch(() => {});
    await rm(tempPath, { force: true }).catch(() => {});
  }
}

async function readOptional(path) {
  try {
    return await readFile(path, 'utf8');
  } catch (error) {
    if (error?.code === 'ENOENT') return '';
    throw error;
  }
}

export async function generateSupabaseTypes({
  repoRoot = DEFAULT_REPO_ROOT,
  environment = process.env,
  platform = process.platform,
  runCli = captureCliOutput,
  runLocalPglite = generateOpenClawPgliteTypeOutput,
} = {}) {
  const configPath = join(repoRoot, 'supabase', 'config.toml');
  const linkedRefPath = join(repoRoot, 'supabase', '.temp', 'project-ref');
  const packagePath = join(repoRoot, 'package.json');
  const localConfigPath = join(repoRoot, 'CLAUDE.local.md');
  const outputPath = join(repoRoot, 'src', 'integrations', 'supabase', 'types.ts');
  const [configToml, linkedProjectRef, packageJson, localConfig] = await Promise.all([
    readOptional(configPath),
    readOptional(linkedRefPath),
    readOptional(packagePath),
    readOptional(localConfigPath),
  ]);
  const source = environment.SUPABASE_TYPES_SOURCE === 'local' ? 'local' : 'project';
  const localEngine =
    source === 'local'
      ? environment.SUPABASE_TYPES_LOCAL_ENGINE || 'cli'
      : 'cli';
  if (!['cli', 'pglite'].includes(localEngine)) {
    throw new Error('SUPABASE_TYPES_LOCAL_ENGINE must be cli or pglite.');
  }
  const projectRef =
    source === 'local'
      ? ''
      : resolveProjectRef({ configToml, linkedProjectRef, packageJson });
  const accessToken =
    source === 'local' ? '' : extractSupabaseAccessToken({ environment, localConfig });
  const invocation = buildSupabaseCliInvocation(projectRef, platform, {
    npmExecPath: environment.npm_execpath,
    source,
  });
  const childEnvironment = buildMinimalChildEnvironment(
    environment,
    source === 'project' ? { SUPABASE_ACCESS_TOKEN: accessToken } : {},
  );

  let contents;
  try {
    if (source === 'local' && localEngine === 'pglite') {
      const baseline = await readOptional(outputPath);
      if (!baseline) {
        throw new Error('PGlite type generation requires the current generated baseline.');
      }
      const generated = await runLocalPglite({
        repoRoot,
        environment: childEnvironment,
        platform,
      });
      contents = buildGeneratedTypesFile(
        mergeOpenClawGeneratedTypes(baseline, generated),
      );
    } else {
      const result = await runCli({
        ...invocation,
        cwd: repoRoot,
        env: childEnvironment,
      });
      if (result.exitCode !== 0) {
        const details = redactSecrets(result.stderr.trim(), [accessToken]).slice(0, 2_000);
        throw new Error(
          `Supabase CLI exited with code ${result.exitCode}.${details ? ` ${details}` : ''}`,
        );
      }
      contents = buildGeneratedTypesFile(result.stdout);
    }
  } catch (error) {
    throw new Error(
      `Could not generate Supabase types: ${redactSecrets(error?.message, [accessToken])}`,
    );
  } finally {
    delete childEnvironment.SUPABASE_PAT;
    delete childEnvironment.SUPABASE_ACCESS_TOKEN;
  }

  await atomicWriteUtf8(outputPath, contents);
  return outputPath;
}

async function main() {
  const outputPath = await generateSupabaseTypes();
  process.stdout.write(`Generated Supabase types: ${relative(DEFAULT_REPO_ROOT, outputPath)}\n`);
}

const entryPoint = process.argv[1] ? pathToFileURL(resolve(process.argv[1])).href : '';
if (entryPoint === import.meta.url) {
  main().catch((error) => {
    console.error(redactSecrets(error?.message ?? error));
    process.exitCode = 1;
  });
}
